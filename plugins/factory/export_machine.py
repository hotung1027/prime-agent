
"""Generate the factory machine library entry from roles.py (single source of truth).

Writes ~/.prime/agent/machines/staged-delivery/MACHINE.md: the core FSM
    research -> plan -> implement -> review -> verify -> merge
with a failed review or verification looping back to implement. Stage gates
(security/profiling/infrastructure/cicd/visual) stay in the Python runner, because
which gates apply depends on the stage - the factory machine cannot be parameterised.

Run: python3 export_machine.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
import sys
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import roles  # noqa: E402

MACHINE_DIR = Path.home() / ".prime" / "agent" / "machines" / "staged-delivery"
ARM_PARAM = {"spec_path": "plan.spec_path", "impl": "implement.impl",
             "verdict": "review.verdict", "check": "verify.check"}

# state -> (role id, inputs[names bound from other states], outputs, max_entries)
PLAN = {
    "research": ("researcher", ["task"], [("context", "json")], 1),
    "plan": ("planner", ["research"], [("spec_path", "json")], 1),
    "implement": ("implementer", ["spec_path", "verdict", "check"], [("impl", "json")], 4),
    "review": ("reviewer", ["spec_path", "impl"], [("verdict", "json")], 4),
    "verify": ("verifier", ["spec_path", "impl"], [("check", "json")], 4),
    "merge": ("merger", ["spec_path", "impl", "verdict", "check"], [("report", "text")], 1),
}
SOURCES = {
    "task": None,                     # entry state: the brief is read from the run dir
    "research": ("research", "context"),
    "spec_path": ("plan", "spec_path"),
    "impl": ("implement", "impl"),
    "verdict": ("review", "verdict"),
    "check": ("verify", "check"),
}


def build():
    states = []
    for state_id, (role_id, inputs, outputs, max_entries) in PLAN.items():
        prompt = None
        for text, _key in [(roles.ROLES[role_id][0], roles.ROLES[role_id][1])]:
            prompt = text
        sub = {"prompt": prompt}
        state = {"id": state_id, "subagent": sub,
                 "outputs": [{"name": n, "type": t} for n, t in outputs]}
        if state_id == "research":
            state["entry"] = True
        else:
            port_inputs = []
            for name in inputs:
                src = SOURCES[name]
                if src is None:
                    continue
                optional = state_id == "implement" and name in ("verdict", "check")
                port = {"name": name, "type": "json", "from": f"{src[0]}.{src[1]}"}
                if optional:
                    port["optional"] = True
                port_inputs.append(port)
            if port_inputs:
                state["inputs"] = port_inputs
        if max_entries > 1:
            state["max_entries"] = max_entries
        states.append(state)

    machine = {
        "run": {"budget_ms": 2_400_000, "max_parallel": 4, "max_transitions": 60,
                "failure_policy": "escalate"},
        "states": states,
        "transitions": [
            {"from": "research", "to": "plan"},
            {"from": "plan", "to": "implement"},
            {"from": "implement", "to": "review"},
            {"from": "review", "to": "implement",
             "when": {"output": "verdict", "path": "verdict.approved", "op": "eq", "value": False}},
            {"from": "review", "to": "verify",
             "when": {"output": "verdict", "path": "verdict.approved", "op": "eq", "value": True}},
            {"from": "verify", "to": "implement",
             "when": {"output": "check", "path": "check.passed", "op": "eq", "value": False}},
            {"from": "verify", "to": "merge",
             "when": {"output": "check", "path": "check.passed", "op": "eq", "value": True}},
        ],
    }
    return machine


def main():
    import rlm.factory as F
    machine = build()
    errors = F.validate_factory_machine(machine)
    if errors:
        raise SystemExit("invalid machine:\n- " + "\n- ".join(errors))
    MACHINE_DIR.mkdir(parents=True, exist_ok=True)
    body = f"""---
name: staged-delivery
description: {json.dumps("Core delivery FSM generated from roles.py: research -> plan -> implement -> review -> verify -> merge, with review/verify looping back to the implementer.")}
version: 1
author: prime-agent
---

# staged-delivery

Generated by `~/.prime/agent/pipelines/export_machine.py` from `roles.py` - edit the role prompts
there, not here. Gates (security, profiling, infrastructure, cicd, visual) are NOT in this machine:
which of them apply depends on the stage, and a factory machine cannot be parameterised, so the
Python runner (`engine.run_stages(brief, stage=...)`) owns the stage logic.

```machine-spec
{json.dumps(machine, indent=2)}
```
"""
    (MACHINE_DIR / "MACHINE.md").write_text(body)
    print(f"wrote {MACHINE_DIR/'MACHINE.md'} ({len(body)} bytes, {len(states_of(machine))} states)")


def states_of(machine):
    return machine["states"]


if __name__ == "__main__":
    main()
